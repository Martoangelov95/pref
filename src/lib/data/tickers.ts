function normalizeTickerSymbol(ticker: string): string {
  return ticker.replace(/-$/, ''); // strip trailing hyphen
}

function isValidTicker(ticker: string): boolean {
  if (!ticker || ticker === '4' || ticker.trim() === '') return false;
  return /^[A-Z0-9][A-Z0-9\-\.]*[A-Z0-9]$/.test(ticker.trim()) ||
    /^[A-Z]+$/.test(ticker.trim()) ||
    /^[A-Z]+-[A-Z0-9]+$/.test(ticker.trim());
}

function resolveCommonTicker(ticker: string): string {
  if (COMMON_OVERRIDES[ticker]) return COMMON_OVERRIDES[ticker];
  const normalized = normalizeTickerSymbol(ticker);
  if (COMMON_OVERRIDES[normalized]) return COMMON_OVERRIDES[normalized];
  return deriveCommon(normalized);
}

// Build the final deduplicated ticker entries
const seen = new Set<string>();
export const TICKER_LIST: TickerEntry[] = RAW_TICKERS
  .map(t => normalizeTickerSymbol(t.trim()))
  .filter(t => isValidTicker(t))
  .filter(t => {
    if (seen.has(t)) return false;
    seen.add(t);
    return true;
  })
  .map(ticker => ({
    ticker,
    commonTicker: resolveCommonTicker(ticker),
  }));

export const TICKER_SYMBOLS: string[] = TICKER_LIST.map(e => e.ticker);

export const COMMON_TICKER_MAP: Record<string, string> = Object.fromEntries(
  TICKER_LIST.map(e => [e.ticker, e.commonTicker])
);
