/**
 * Maps preferred stock tickers to their underlying common stock ticker.
 * For standard hyphenated preferreds (e.g. BAC-S), the common is the root (BAC).
 * OTC preferreds with 'P' suffix (e.g. BANFP) map to BAN, etc. — these are
 * manually curated where the root extraction rule doesn't apply.
 * Tickers ending in '-' or clearly malformed are filtered out.
 */

function deriveCommon(ticker: string): string {
  // Handle hyphenated preferreds: BAC-S → BAC, JPM-L → JPM
  if (ticker.includes('-')) {
    return ticker.split('-')[0];
  }
  // OTC preferreds often end in P, Z, N, L, M — strip trailing suffix letters
  // Heuristic: if last 1-2 chars are uppercase letters and not the whole ticker, strip them
  // This is a best-effort; manual overrides below take precedence
  return ticker;
}

